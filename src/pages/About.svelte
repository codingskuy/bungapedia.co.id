  <h1>Tentang Bungapedia</h1>
  <p class="lede">Selamat datang di Bungapedia, jantung grosir bunga Indonesia. Kami bukan sekadar pedagang bunga nasional — perjalanan kami anyaman empat generasi yang bermula dari kebun keluarga di kaki Gunung Tangkuban Parahu.</p>
  <h2>Perjalanan kami</h2>
  <p>Berdiri 2009, Bungapedia tumbuh dari benih kecintaan keluarga Suryana terhadap bunga. Berawal dari 2 hektar kebun mawar di Bandung, kini kami bermitra dengan 40+ kebun di Bandung, Batu, Dieng, dan Bali — memadukan kehangatan tradisional dengan presisi rantai dingin modern.</p>
  <h2>Janji kami</h2>
  <ul class="pledge">
    <li><b>Kualitas tanpa kompromi:</b> hanya kuntum grade A yang lolos sortir — setiap ikat mencerminkan kesegaran kebun kami.</li>
    <li><b>Tradisi bertemu inovasi:</b> kurasi manual petani, didukung stok live & pre-book digital agar kamu selalu selangkah di depan tren.</li>
    <li><b>Pelanggan di depan:</b> setiap toko — dari kios pasar hingga wedding organizer — adalah bagian keluarga Bungapedia.</li>
  </ul>
  <h2>Komunitas & kebersamaan</h2>
  <p>Kami mengundangmu melampaui sekadar transaksi: workshop merangkai bulanan di Hub Jakarta, grup tani-florist, dan program magang perangkai muda. Berkumpulnya seniman dan pecinta bunga dalam satu semangat.</p>
  <h2>Bergabung dengan keluarga Bungapedia</h2>
  <p>Tertarik pada lanskap dinamis tempat kecintaan pada bunga bertemu dedikasi profesional? Lihat lowongan atau jadi mitra kebun.</p>
